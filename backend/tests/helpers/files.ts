import { crc32 } from "node:zlib";
import { PDFDocument, PDFName, StandardFonts } from "pdf-lib";

export async function makePdf(pages: number): Promise<Buffer> {
  const doc = await PDFDocument.create();
  const font = await doc.embedFont(StandardFonts.Helvetica);
  for (let i = 0; i < pages; i++) {
    const page = doc.addPage([595, 842]);
    page.drawText(`Page ${i + 1}`, { x: 50, y: 780, size: 18, font });
  }
  return Buffer.from(await doc.save({ useObjectStreams: false }));
}

export async function makePdfWithJavascript(): Promise<Buffer> {
  const doc = await PDFDocument.create();
  doc.addPage();
  const js = doc.context.obj({ Type: "Action", S: "JavaScript", JS: "app.alert('x')" });
  doc.catalog.set(PDFName.of("OpenAction"), doc.context.register(js));
  return Buffer.from(await doc.save({ useObjectStreams: false }));
}

